# -------------------- chemistry-aware post-hoc expansion --------------------

def _edge_wbo(g, a, b):
    """WBO for any atom pair in the complete weighted graph."""
    if a == b:
        return 0.0
    mat = g.graph.get("wbo_matrix")
    if mat is not None:
        return float(mat[a, b])
    if g.has_edge(a, b):
        return float(g[a][b].get("wbo", 0.0))
    return 0.0


def _growth_edge_supported(w_R, w_P, iso_tol):
    """True when a popped traversal edge has a real weighted counterpart.

    The complete-graph iso tolerance is deliberately permissive so changed
    bonds can survive as mechanism boundaries.  But the edge used to grow an
    unchanged island must still be anchored in the target graph; otherwise a
    terminal atom, especially H, can float to any same-element atom because
    `abs(~1.0 - 0.0) <= iso_tol` when `iso_tol == 1`.
    """
    w_R = float(w_R)
    w_P = float(w_P)
    if abs(w_R - w_P) > iso_tol:
        return False
    if w_R > 0.0 and w_P <= 0.0:
        return False
    return abs(_wbo_bucket(w_R) - _wbo_bucket(w_P)) <= 1


def _v_equivalence_class(r, mapping, g_R, g_P, iso_tol=1.0):
    """For an already-mapped atom r with image v = mapping[r], find all
    OTHER P atoms v' that are locally equivalent to v under `mapping`:
      - same element
      - same WBO to mapping[u] for every u in r's R-fragment neighbors
      - same multiset of (element, WBO) for unmapped P-neighbors

    These are the atoms r could have mapped to interchangeably. Returns
    a list of v's including the original v as the first element."""
    v0 = mapping[r]
    n_el = g_R.nodes[r]['element']
    bonded_in_frag = [u for u in g_R.neighbors(r) if u in mapping]
    if not bonded_in_frag:
        return [v0]
    used_p = set(mapping.values())
    sig0 = None
    candidates = [v0]
    # Reference signature for v0
    def sig_of(v):
        unmapped = []
        for w in g_P.neighbors(v):
            if w in used_p or w == v: continue
            unmapped.append((g_P.nodes[w]['element'], round(g_P[v][w]['wbo'], 2)))
        return tuple(sorted(unmapped))
    sig0 = sig_of(v0)
    for v in g_P.nodes():
        if v == v0: continue
        if v in used_p: continue
        if g_P.nodes[v]['element'] != n_el: continue
        # WBO match to mapped fragment neighbors
        ok = True
        for u in bonded_in_frag:
            wR = _edge_wbo(g_R, u, r)
            wP = _edge_wbo(g_P, mapping[u], v)
            if abs(wR - wP) > iso_tol: ok = False; break
        if not ok: continue
        if sig_of(v) != sig0: continue
        candidates.append(v)
    return candidates


def expand_chemistry_relevant_atoms(mapping, broken_R_atoms, g_R, g_P, iso_tol=1.0):
    """Given a canonical bijection and the set of R-atoms that participate
    in broken/formed bonds, enumerate alternative bijections by swapping
    each chemistry-relevant atom's image with members of its equivalence
    class. Returns a list of (mapping, swap_path) tuples, where the
    canonical mapping is first.

    Each alternative is generated by a SWAP: r -> v', and the previous
    occupant of v' -> mapping[r]. We then re-validate WBO consistency on
    every R-edge among the mapped atoms.
    """
    alternatives = [(dict(mapping), [])]
    seen_keys = {tuple(sorted(mapping.items()))}
    for r in broken_R_atoms:
        if r not in mapping: continue
        eqv = _v_equivalence_class(r, mapping, g_R, g_P, iso_tol=iso_tol)
        if len(eqv) <= 1: continue
        v_orig = mapping[r]
        inv = {p: q for q, p in mapping.items()}
        for v_new in eqv[1:]:  # skip the original
            r2 = inv.get(v_new)
            new_m = dict(mapping)
            new_m[r] = v_new
            if r2 is not None:
                new_m[r2] = v_orig
            # Validate all R-edges still match
            valid = True
            for u in new_m:
                for w in g_R.neighbors(u):
                    if w not in new_m or u >= w: continue
                    wR = _edge_wbo(g_R, u, w)
                    pu, pw = new_m[u], new_m[w]
                    if abs(wR - _edge_wbo(g_P, pu, pw)) > iso_tol:
                        valid = False; break
                if not valid: break
            if not valid: continue
            key = tuple(sorted(new_m.items()))
            if key in seen_keys: continue
            seen_keys.add(key)
            alternatives.append((new_m, [(r, v_new)]))
    return alternatives


# -------------------- automorphism-aware orbit dedup --------------------

def _color_refine_orbits(g, iters=20):
    """Iterated color refinement (1-WL / Morgan extended connectivity) on
    an UNLABELED graph. Returns dict node -> int orbit_id such that two
    nodes have the same orbit_id iff they're indistinguishable under
    iterated neighbor-multiset refinement.

    Used to detect symmetric P-atom orbits: bijections that differ only
    by swapping P-atoms in the same orbit produce identical chemistry
    signatures and can be safely collapsed in the cand list.

    For molecules with little symmetry, every atom ends up in its own
    orbit (no collapse). For benzene rings, methyl Hs, B12 carborane,
    etc., symmetric atoms share an orbit and the K-factorial cand
    explosion is avoided.

    Algorithmic correctness: this is the standard 1-WL test used in
    InChI / RDKit canonical SMILES. It's exact for almost all molecular
    graphs and known to fail only on a small class of regular graphs
    (where 2-WL or full automorphism check is needed). For chemistry
    we're safe.
    """
    elements = nx.get_node_attributes(g, 'element')
    # Initial color: just element
    colors = {v: elements.get(v, '') for v in g.nodes()}
    # WBO bucket width: 0.2 so atoms whose WBO differs by ≤0.1 from xtb
    # noise (or geometry distortion at TS) end up in the same orbit.
    # round(x / 0.2) * 0.2 → bucket centers at 0.0, 0.2, 0.4, ...
    def _bucket(w):
        return int(round(w * 5))   # 0.2-wide buckets, integer-keyed
    for _ in range(iters):
        new = {}
        for v in g.nodes():
            nbr = tuple(sorted(
                (colors[w], _bucket(_edge_wbo(g, v, w)))
                for w in g.nodes()
                if w != v
            ))
            new[v] = (colors[v], nbr)
        # Compact to small ints (cheap downstream hashing)
        unique = {c: i for i, c in
                  enumerate(sorted(set(new.values()), key=str))}
        new_int = {v: unique[new[v]] for v in g.nodes()}
        if new_int == colors:
            break
        colors = new_int
    return colors


def _cand_canon_signature(cand, p_orbits):
    """Canonical signature for a cand under unlabeled-g_P orbits.

    Two cands with the same signature differ only by permuting P-atoms
    within their unlabeled orbits — they're spectator-equivalent and
    produce identical chemistry signatures.
    """
    return tuple(sorted((r, p_orbits[p]) for r, p in cand.items()))


def _dedup_cands_by_orbit(cands, p_orbits):
    """Collapse cands that differ only by g_P orbit permutations."""
    if not cands or p_orbits is None or len(cands) == 1:
        return cands
    seen = {}
    for c in cands:
        sig = _cand_canon_signature(c, p_orbits)
        if sig not in seen:
            seen[sig] = c
    return list(seen.values())


def _wbo_bucket(w):
    return int(round(float(w) * 5))


def _orbit_id(orbits, node):
    return orbits[node] if orbits is not None else node


@dataclass(frozen=True)
class _SymBlock:
    """A local symmetry class inside one partial candidate.

    `r_atoms` are already present in the growing R fragment.  `p_atoms` is
    the target pool they occupy up to local symmetry; the candidate stores a
    deterministic concrete witness, but extension/dedup reason over the pool.
    Initial seed pools are not extendable because they represent "where the
    anchor could be", not a sibling class around an already chosen anchor.
    """
    r_atoms: tuple
    p_atoms: tuple
    extendable: bool = True

    def __post_init__(self):
        object.__setattr__(self, 'r_atoms', tuple(sorted(set(self.r_atoms))))
        object.__setattr__(self, 'p_atoms', tuple(sorted(set(self.p_atoms))))

    @property
    def open(self):
        return len(self.r_atoms) < len(self.p_atoms)

    @property
    def complete(self):
        return len(self.r_atoms) >= len(self.p_atoms)


class _SymCand:
    """Compressed partial mapping with symmetry blocks and one witness.

    The public alignment API still consumes concrete dict mappings.  Inside
    growth, this object keeps target pools grouped so a K-fold symmetric target
    produces one candidate instead of K concrete bijections.  `mapping` is the
    deterministic witness used for cheap WBO existence checks.
    """
    __slots__ = ('mapping', 'blocks', 'exact_fixed')

    def __init__(self, mapping=None, blocks=(), exact_fixed=()):
        blocks = tuple(blocks)
        block_r = {r for b in blocks for r in b.r_atoms}
        raw = dict(mapping or {})
        m = {r: p for r, p in raw.items() if r not in block_r}
        used = set(m.values())
        for b in blocks:
            if len(b.r_atoms) > len(b.p_atoms):
                raise ValueError("symmetry block has more R atoms than P atoms")
            for r in b.r_atoms:
                if r not in raw:
                    continue
                p = raw[r]
                if p not in b.p_atoms or p in used:
                    raise ValueError("symmetry block witness conflicts with fixed atoms")
                m[r] = p
                used.add(p)
            available = [p for p in b.p_atoms if p not in used]
            missing = [r for r in b.r_atoms if r not in m]
            if len(available) < len(missing):
                raise ValueError("symmetry block witness conflicts with fixed atoms")
            for r, p in zip(missing, available):
                m[r] = p
                used.add(p)
        self.mapping = m
        self.blocks = blocks
        self.exact_fixed = frozenset(exact_fixed)

    def __contains__(self, r):
        return r in self.mapping

    def __getitem__(self, r):
        return self.mapping[r]

    def get(self, r, default=None):
        return self.mapping.get(r, default)

    def items(self):
        return self.mapping.items()

    def values(self):
        return self.mapping.values()

    def materialize(self):
        return dict(self.mapping)

    def has_open_choice(self):
        return any(b.open for b in self.blocks)

    def with_fixed(self, r, p):
        if r in self.mapping:
            return self if self.mapping[r] == p else None
        if p in self.mapping.values():
            return None
        m = dict(self.mapping)
        m[r] = p
        try:
            return _SymCand(m, self.blocks, self.exact_fixed)
        except ValueError:
            return None

    def with_new_block(self, r, p_atoms, extendable=True):
        p_atoms = tuple(sorted(set(p_atoms)))
        if not p_atoms:
            return None
        if len(p_atoms) == 1:
            return self.with_fixed(r, p_atoms[0])
        if r in self.mapping:
            return None
        b = _SymBlock((r,), p_atoms, extendable=extendable)
        try:
            return _SymCand(self.mapping, self.blocks + (b,),
                            self.exact_fixed)
        except ValueError:
            return None

    def with_extended_block(self, block_idx, r):
        if r in self.mapping:
            return None
        blocks = list(self.blocks)
        b = blocks[block_idx]
        if not b.extendable or b.complete:
            return None
        blocks[block_idx] = _SymBlock(b.r_atoms + (r,), b.p_atoms,
                                      extendable=b.extendable)
        try:
            return _SymCand(self.mapping, blocks, self.exact_fixed)
        except ValueError:
            return None

    def with_witness(self, assignments):
        r_to_block = {}
        for idx, block in enumerate(self.blocks):
            for r in block.r_atoms:
                r_to_block[r] = idx
        touched_blocks = {
            r_to_block[r] for r in assignments
            if r in r_to_block
        }
        m = {
            r: p for r, p in self.mapping.items()
            if r not in r_to_block or r_to_block[r] not in touched_blocks
        }
        m.update(assignments)
        try:
            return _SymCand(m, self.blocks, self.exact_fixed)
        except ValueError:
            return None

    def structural_signature(self, g_R, g_P, r_orbits=None, p_orbits=None):
        block_r = {r for b in self.blocks for r in b.r_atoms}
        fixed = tuple(sorted(
            (('exact', r) if r in self.exact_fixed
             else ('orbit', _orbit_id(r_orbits, r)),
             ('exact', p) if r in self.exact_fixed
             else ('orbit', _orbit_id(p_orbits, p)))
            for r, p in self.mapping.items()
            if r not in block_r
        ))
        blocks = tuple(sorted(
            (
                tuple(sorted(_orbit_id(r_orbits, r) for r in b.r_atoms)),
                len(b.r_atoms),
                tuple(sorted(_orbit_id(p_orbits, p) for p in b.p_atoms)),
                len(b.p_atoms),
                bool(b.extendable),
            )
            for b in self.blocks
        ))
        return fixed, blocks


def _cand_map(cand):
    return cand.materialize() if isinstance(cand, _SymCand) else dict(cand)


def _cand_possible_p_atoms(cand):
    atoms = set(_cand_map(cand).values())
    if isinstance(cand, _SymCand):
        for block in cand.blocks:
            atoms.update(block.p_atoms)
    return atoms


def _cand_has_open_choice(cand):
    return isinstance(cand, _SymCand) and cand.has_open_choice()


def _group_nodes_by_signature(nodes, sig_fn):
    groups = defaultdict(list)
    for node in sorted(nodes):
        groups[sig_fn(node)].append(node)
    return [tuple(vs) for _, vs in sorted(groups.items(), key=lambda kv: str(kv[0]))]


def _p_relation_signature(cand, v, g_P, p_orbits):
    cm = _cand_map(cand)
    rel = []
    for r, p in sorted(cm.items()):
        if p == v:
            continue
        rel.append((r, _wbo_bucket(_edge_wbo(g_P, p, v))))
    block_rel = []
    if isinstance(cand, _SymCand):
        for i, b in enumerate(cand.blocks):
            edge_wbos = []
            for p in b.p_atoms:
                if p == v:
                    continue
                edge_wbos.append(_wbo_bucket(_edge_wbo(g_P, p, v)))
            block_rel.append((i, v in b.p_atoms, tuple(sorted(edge_wbos))))
    return (g_P.nodes[v].get('element'), _orbit_id(p_orbits, v),
            tuple(rel), tuple(block_rel))


def _r_compatible_with_block(cand, block_idx, n, fragment, g_R, r_orbits):
    if not isinstance(cand, _SymCand):
        return False
    b = cand.blocks[block_idx]
    if not b.extendable or b.complete:
        return False
    if r_orbits is not None:
        n_orbit = r_orbits[n]
        if any(r_orbits[r] != n_orbit for r in b.r_atoms):
            return False
    block_r = set(b.r_atoms)
    outside = sorted(r for r in fragment if r not in block_r and r in cand.mapping)

    def rel_sig(r):
        out = []
        for x in outside:
            out.append((x, _wbo_bucket(_edge_wbo(g_R, r, x))))
        return tuple(out)

    n_sig = rel_sig(n)
    return all(rel_sig(r) == n_sig for r in b.r_atoms)


def _boundary_signature(cand, g_R, g_P, fragment=None, deferred_edges=(),
                        r_orbits=None, p_orbits=None, inv=None):
    if not fragment or not deferred_edges:
        return ()
    fragment = set(fragment)
    cm = _cand_map(cand)
    used_possible = _cand_possible_p_atoms(cand)
    inv_used = set(inv or ())

    boundary = set()
    deferred_by_outside = defaultdict(list)
    for raw in deferred_edges or ():
        edge = tuple(raw)
        if len(edge) != 2:
            continue
        a, b = edge
        a_in = a in fragment
        b_in = b in fragment
        if a_in == b_in:
            continue
        inside, outside = (a, b) if a_in else (b, a)
        boundary.add(outside)
        deferred_by_outside[outside].append(inside)

    mapped_rs = sorted(r for r in fragment if r in cm)
    out = []
    for x in sorted(boundary):
        r_vec = tuple(
            (r, _orbit_id(r_orbits, r), _wbo_bucket(_edge_wbo(g_R, x, r)))
            for r in mapped_rs
        )
        target_sigs = []
        x_el = g_R.nodes[x].get('element')
        for v in g_P.nodes():
            if v in inv_used or v in used_possible:
                continue
            if g_P.nodes[v].get('element') != x_el:
                continue
            target_sigs.append(_p_relation_signature(cand, v, g_P, p_orbits))
        counts = Counter(target_sigs)
        p_vec = tuple(sorted(counts.items(), key=lambda item: str(item[0])))
        deferred = tuple(sorted(
            (r, _orbit_id(r_orbits, r), _wbo_bucket(_edge_wbo(g_R, x, r)))
            for r in deferred_by_outside.get(x, [])
        ))
        out.append((_orbit_id(r_orbits, x), x_el, r_vec, deferred, p_vec))
    return tuple(out)


def _dedup_sym_cands(cands, g_R, g_P, r_orbits=None, p_orbits=None,
                     fragment=None, deferred_edges=(), inv=None):
    if not cands:
        return cands
    seen = {}
    for cand in cands:
        if isinstance(cand, _SymCand):
            internal = cand.structural_signature(g_R, g_P, r_orbits, p_orbits)
        elif p_orbits is not None:
            internal = _cand_canon_signature(cand, p_orbits)
        else:
            internal = tuple(sorted(cand.items()))
        boundary = _boundary_signature(
            cand, g_R, g_P, fragment=fragment,
            deferred_edges=deferred_edges, r_orbits=r_orbits,
            p_orbits=p_orbits, inv=inv)
        sig = (internal, boundary)
        if sig not in seen:
            seen[sig] = cand
    return list(seen.values())


def _sym_block_indexes(cand):
    r_to_block = {}
    p_to_block = {}
    if isinstance(cand, _SymCand):
        for idx, block in enumerate(cand.blocks):
            for r in block.r_atoms:
                r_to_block[r] = idx
            for p in block.p_atoms:
                p_to_block[p] = idx
    return r_to_block, p_to_block


def _refine_sym_assignments(cand, assignments):
    """Freeze selected block assignments and shrink the remaining pools.

    This is used when a new atom is valid only under a particular assignment
    inside an existing symmetry block.  Keeping the old block would imply the
    new fixed atom is independent of that block, which is false for cases like
    R37=P38 <=> R104=P119 vs R37=P36 <=> R104=P123.
    """
    if not isinstance(cand, _SymCand):
        m = dict(cand)
        used = {p for r, p in m.items() if r not in assignments}
        for r, p in assignments.items():
            if p in used:
                return None
            m[r] = p
            used.add(p)
        return m

    assignments = dict(assignments)
    if len(set(assignments.values())) != len(assignments):
        return None

    r_to_block, _ = _sym_block_indexes(cand)
    block_r = set(r_to_block)
    m = {r: p for r, p in cand.mapping.items() if r not in block_r}
    used = set(m.values())
    for r, p in sorted(assignments.items()):
        if p in used and m.get(r) != p:
            return None
        m[r] = p
        used.add(p)

    new_blocks = []
    for block in cand.blocks:
        remaining_r = tuple(r for r in block.r_atoms if r not in assignments)
        remaining_p = tuple(p for p in block.p_atoms
                            if p not in assignments.values())
        if not remaining_r:
            continue
        if len(remaining_r) > len(remaining_p):
            return None
        for r in remaining_r:
            p = cand.mapping.get(r)
            if p in remaining_p and p not in used:
                m[r] = p
                used.add(p)
        new_blocks.append(_SymBlock(remaining_r, remaining_p,
                                    extendable=block.extendable))
    exact_fixed = set(cand.exact_fixed)
    try:
        return _SymCand(m, tuple(new_blocks), exact_fixed=exact_fixed)
    except ValueError:
        return None


def _support_witness_for_value(cand, n, v_n, bonded_in_frag, r_wbos,
                               g_P, iso_tol, join_block_idx=None,
                               strict_r_wbos=None,
                               max_states=SYM_SUPPORT_MAX_STATES):
    """Find a concrete witness that supports R[n] -> P[v_n].

    `_SymCand` blocks represent a pool of legal P atoms, but the stored
    mapping is only one witness.  Extension must therefore ask whether some
    assignment inside each unresolved block can satisfy the new edge pattern,
    not whether the current witness happens to satisfy it.
    """
    strict_by_r = dict(strict_r_wbos or ())

    def _pair_ok(r_atom, w_R, p_atom):
        w_P = _edge_wbo(g_P, p_atom, v_n)
        if r_atom in strict_by_r:
            return _growth_edge_supported(strict_by_r[r_atom], w_P, iso_tol)
        return abs(w_R - w_P) <= iso_tol

    if not isinstance(cand, _SymCand):
        used = set(cand.values())
        if v_n in used and cand.get(n) != v_n:
            return None
        support = {}
        for u, w in r_wbos:
            if u not in cand:
                return None
            p_u = cand[u]
            if p_u == v_n:
                return None
            if not _pair_ok(u, w, p_u):
                return None
        return support

    r_to_block, p_to_block = _sym_block_indexes(cand)
    block_r = set(r_to_block)
    fixed_used = {p for r, p in cand.mapping.items() if r not in block_r}
    if v_n in fixed_used and cand.get(n) != v_n:
        return None
    value_block = p_to_block.get(v_n)
    if value_block is not None and value_block != join_block_idx:
        return None
    if join_block_idx is not None:
        block = cand.blocks[join_block_idx]
        if v_n not in block.p_atoms or not block.open:
            return None

    by_block = defaultdict(list)
    support = {}
    w_by_r = {u: w for u, w in r_wbos}
    for u in bonded_in_frag:
        if u not in cand.mapping:
            return None
        bidx = r_to_block.get(u)
        if bidx is None:
            p_u = cand.mapping[u]
            if p_u == v_n:
                return None
            if not _pair_ok(u, w_by_r[u], p_u):
                return None
            continue
        by_block[bidx].append((u, w_by_r[u]))

    for bidx, items in by_block.items():
        block = cand.blocks[bidx]
        reserved = set()
        if bidx == join_block_idx:
            reserved.add(v_n)
        domains = []
        available_pool = [p for p in block.p_atoms if p not in reserved]
        for u, w in items:
            vals = []
            for p in available_pool:
                if _pair_ok(u, w, p):
                    vals.append(p)
            if not vals:
                return None
            domains.append((u, vals))
        if all(set(vals) == set(available_pool) for _, vals in domains):
            continue
        domains.sort(key=lambda item: (len(item[1]), item[0]))
        chosen = {}
        used = set(reserved)
        states = 0

        def backtrack(pos):
            nonlocal states
            states += 1
            if states > max_states:
                return False
            if pos == len(domains):
                return True
            u, vals = domains[pos]
            for p in vals:
                if p in used:
                    continue
                used.add(p)
                chosen[u] = p
                if backtrack(pos + 1):
                    return True
                chosen.pop(u, None)
                used.remove(p)
            return False

        if not backtrack(0):
            return None
        support.update(chosen)
    return support


def _force_sym_value(cand, r, p, fragment, g_R, r_orbits, p_orbits):
    if not isinstance(cand, _SymCand):
        if r in cand:
            return cand if cand[r] == p else None
        if p in cand.values():
            return None
        nc = dict(cand)
        nc[r] = p
        return nc
    r_to_block, p_to_block = _sym_block_indexes(cand)
    if r in cand.mapping:
        current = cand.mapping[r]
        if current == p:
            return cand
        block_idx = r_to_block.get(r)
        if block_idx is None or p not in cand.blocks[block_idx].p_atoms:
            return None
        assignment = {r: p}
        for other in cand.blocks[block_idx].r_atoms:
            if other != r and cand.mapping.get(other) == p:
                assignment[other] = current
                break
        return _refine_sym_assignments(cand, assignment)
    block_idx = p_to_block.get(p)
    if block_idx is not None:
        if not _r_compatible_with_block(cand, block_idx, r, fragment,
                                        g_R, r_orbits):
            return None
        nc = cand.with_extended_block(block_idx, r)
        return _refine_sym_assignments(nc, {r: p}) if nc is not None else None
    block_r = set(r_to_block)
    fixed_used = {v for rr, v in cand.mapping.items() if rr not in block_r}
    if p in fixed_used:
        return None
    return cand.with_fixed(r, p)


