def _set_unique(cands):
    """True iff there is at most one fully resolved distinct mapping.

    Earlier this used `frozenset(c.values())` as the equivalence key,
    which collapses every full-bijection candidate to one (since they
    all use the same value-set), silently dropping symmetric variants
    like (R87->IG87, R88->IG88) vs (R87->IG88, R88->IG87). The right
    equivalence for our use is the full bijection itself.  Compressed
    symmetry candidates with an open target pool are not lockable yet;
    they must either absorb enough context or reach saturation first."""
    if not cands:
        return False
    if any(_cand_has_open_choice(c) for c in cands):
        return False
    if len(cands) == 1:
        return True
    sig0 = tuple(sorted(_cand_map(cands[0]).items()))
    return all(tuple(sorted(_cand_map(c).items())) == sig0 for c in cands[1:])


def _push_edges_from(heap, used_edges, g_R, atom, fragment, graph_floor):
    """Push all not-yet-seen outgoing traversal edges of `atom` into the heap."""
    for nb in g_R.neighbors(atom):
        if nb in fragment:
            continue
        edge = frozenset({atom, nb})
        if edge in used_edges:
            continue
        w = g_R[atom][nb]['wbo']
        if w >= graph_floor:
            heapq.heappush(heap, (-w, atom, nb))


def _compute_all_isos_FROM_SCRATCH(fragment, g_R, g_P, mapping, inv, iso_tol,
                      islands_R, max_isos=2000):
    """SLOW: NetworkX subgraph_isomorphisms_iter from scratch.
    Kept for verification; live growth uses `_extend_sym_cands`, which
    applies the same local element/WBO constraints while grouping
    orbit-equivalent targets before child candidates are materialized."""
    sub_R = g_R.subgraph(fragment).copy()
    forced = {r: mapping[r] for r in fragment if r in mapping}
    def nm(nP, nR): return nR['element'] == nP['element']
    def em(eP, eR): return abs(eR['wbo'] - eP['wbo']) <= iso_tol
    matcher = nx.algorithms.isomorphism.GraphMatcher(g_P, sub_R, node_match=nm, edge_match=em)
    isos = []
    for raw in matcher.subgraph_isomorphisms_iter():
        rev = {r: p for p, r in raw.items()}
        ok = True
        for r in fragment:
            if r in forced and rev.get(r) != forced[r]: ok = False; break
            elif r not in forced and rev.get(r) in inv: ok = False; break
        if ok:
            isos.append(rev)
            if len(isos) >= max_isos: break
    return isos


def _extend_cands_incremental(cands, fragment_old, n, g_R, g_P, mapping, inv,
                               iso_tol, islands_R):
    """Legacy concrete incremental extension — NO symmetry compression.

    For each cand:
      - bonded = n's R-neighbors that are in fragment_old (must be in cand)
      - v_set = ⋂(P-neighbors of cand[u]) for u in bonded   minus used_p
      - For each v in v_set with element match, WBO match within iso_tol on
        every bonded edge, and v not in global inv: emit cand ∪ {n: v}.

    Provable equivalence to from-scratch subgraph iso: every iso of
    fragment_new restricts to a complete iso of fragment_old, which must be
    among the existing cands (induction from seed-iso initialization). NO
    pruning — symmetric-atom permutations are kept.  The live path uses
    `_extend_sym_cands` instead, so orbit-equivalent target sets are grouped
    before this concrete fanout would happen.

    Whole-island merge: if n in mapping, n's image is forced to mapping[n],
    and the entire island of n is folded into the cand with consistency
    checks on all cross-bonds within (fragment_old ∪ island).
    """
    n_el = g_R.nodes[n]['element']
    bonded_in_frag = [u for u in g_R.neighbors(n) if u in fragment_old]
    if not bonded_in_frag:
        return None
    r_wbos = [(u, g_R[u][n]['wbo']) for u in bonded_in_frag]

    # Determine target P-atom set and other forced atoms (for whole-island).
    if n in mapping:
        if islands_R is not None and n in islands_R:
            iid = islands_R[n]
            island_atoms = [r for r, k in islands_R.items() if k == iid
                            and r not in fragment_old]
        else:
            island_atoms = [n]
        forced_island = {r: mapping[r] for r in island_atoms}
    else:
        island_atoms = [n]
        forced_island = {}

    new_cands = []
    for cand in cands:
        used_p = set(cand.values())
        # n must map to forced[n] if n is in mapping
        if n in mapping:
            v_n = mapping[n]
            if v_n in used_p and cand.get(n) != v_n:
                continue
            # check forced bond constraints
            ok = True
            for u, w in r_wbos:
                if not g_P.has_edge(cand[u], v_n):
                    ok = False; break
                if abs(w - g_P[cand[u]][v_n]['wbo']) > iso_tol:
                    ok = False; break
            if not ok: continue
            base = dict(cand); base[n] = v_n
            # extend with rest of island atoms (force their images)
            extras_ok = True
            for r in island_atoms:
                if r == n or r in base: continue
                p = mapping[r]
                if p in base.values(): extras_ok = False; break
                base[r] = p
            if not extras_ok: continue
            # verify all R-edges among (island ∪ fragment_old) match in P
            check_set = set(base.keys())
            ok = True
            for r in island_atoms:
                for r2 in g_R.neighbors(r):
                    if r2 not in check_set: continue
                    if r >= r2 and r2 in island_atoms: continue
                    wR = g_R[r][r2]['wbo']
                    p, p2 = base[r], base[r2]
                    if not g_P.has_edge(p, p2): ok = False; break
                    if abs(wR - g_P[p][p2]['wbo']) > iso_tol: ok = False; break
                if not ok: break
            if ok:
                new_cands.append(base)
        else:
            # Free extension: enumerate ALL valid v's for atom n. No pruning,
            # no canonical pick, no 1-hop grouping, no frozenset dedup.
            # Each existing cand fans out to every valid v -> new cand.
            # Mathematically equivalent to from-scratch subgraph iso
            # enumeration (each iso of fragment_new restricts to exactly one
            # iso of fragment_old = one of the existing cands), but O(deg)
            # per cand instead of full VF2 backtracking.
            v_set = set(g_P.neighbors(cand[bonded_in_frag[0]]))
            for u in bonded_in_frag[1:]:
                v_set &= set(g_P.neighbors(cand[u]))
            v_set -= used_p
            for v in v_set:
                if v in inv: continue
                if g_P.nodes[v]['element'] != n_el: continue
                if all(abs(w - g_P[cand[u]][v]['wbo']) <= iso_tol
                       for u, w in r_wbos):
                    nc = dict(cand); nc[n] = v
                    new_cands.append(nc)
    return new_cands


def _extend_sym_cands(cands, fragment_old, n, g_R, g_P, mapping, inv,
                      iso_tol, islands_R, p_orbits=None, r_orbits=None,
                      deferred_edges=(), anchor_u=None, anchor_wbo=None):
    """Symmetry-compressed incremental extension.

    Validity is the complete WBO vector from n to the current fragment.  Valid
    target P atoms are grouped by orbit/context signature before constructing
    children.  A symmetric K-way choice therefore creates one `_SymCand` block
    instead of K concrete dicts; downstream code receives a deterministic
    witness only when the island is committed.
    """
    n_el = g_R.nodes[n]['element']
    bonded_in_frag = sorted(fragment_old)
    if not bonded_in_frag:
        return None
    r_wbos = [(u, _edge_wbo(g_R, u, n)) for u in bonded_in_frag]
    strict_r_wbos = {}
    if anchor_u is not None and anchor_u in fragment_old:
        strict_r_wbos[anchor_u] = (
            _edge_wbo(g_R, anchor_u, n)
            if anchor_wbo is None else anchor_wbo
        )

    if n in mapping:
        if islands_R is not None and n in islands_R:
            iid = islands_R[n]
            island_atoms = [r for r, k in islands_R.items() if k == iid
                            and r not in fragment_old]
        else:
            island_atoms = [n]
    else:
        island_atoms = [n]

    new_cands = []
    for raw_cand in cands:
        cand = raw_cand if isinstance(raw_cand, _SymCand) else _SymCand(raw_cand)
        if any(u not in cand.mapping for u in bonded_in_frag):
            continue

        if n in mapping:
            v_n = mapping[n]
            _, p_to_block = _sym_block_indexes(cand)
            join_idx = p_to_block.get(v_n)
            if join_idx is not None and not _r_compatible_with_block(
                    cand, join_idx, n, fragment_old, g_R, r_orbits):
                continue
            support = _support_witness_for_value(
                cand, n, v_n, bonded_in_frag, r_wbos, g_P, iso_tol,
                join_block_idx=join_idx,
                strict_r_wbos=strict_r_wbos)
            if support is None:
                continue
            nc = _force_sym_value(cand, n, v_n, fragment_old, g_R,
                                  r_orbits, p_orbits)
            if nc is None:
                continue
            support[n] = v_n
            nc = nc.with_witness(support) if isinstance(nc, _SymCand) else nc
            if nc is None:
                continue
            extras_ok = True
            for r in island_atoms:
                if r == n:
                    continue
                p = mapping[r]
                nc = _force_sym_value(nc, r, p, fragment_old, g_R,
                                      r_orbits, p_orbits)
                if nc is None:
                    extras_ok = False; break
            if not extras_ok:
                continue

            base = nc.materialize()
            check_set = set(base.keys())
            ok = True
            for r in island_atoms:
                for r2 in sorted(check_set):
                    if r2 == r:
                        continue
                    if r2 not in check_set:
                        continue
                    if r >= r2 and r2 in island_atoms:
                        continue
                    wR = _edge_wbo(g_R, r, r2)
                    p, p2 = base[r], base[r2]
                    if abs(wR - _edge_wbo(g_P, p, p2)) > iso_tol:
                        ok = False; break
                if not ok:
                    break
            if ok:
                new_cands.append(nc)
            continue

        block_join = []
        by_group = defaultdict(list)
        for v in g_P.nodes():
            if v in inv:
                continue
            if g_P.nodes[v]['element'] != n_el:
                continue
            _, p_to_block = _sym_block_indexes(cand)
            join_idx = p_to_block.get(v)
            if join_idx is not None and not _r_compatible_with_block(
                    cand, join_idx, n, fragment_old, g_R, r_orbits):
                continue
            support = _support_witness_for_value(
                cand, n, v, bonded_in_frag, r_wbos, g_P, iso_tol,
                join_block_idx=join_idx,
                strict_r_wbos=strict_r_wbos)
            if support is None:
                continue
            if join_idx is not None:
                block_join.append((join_idx, v, support))
            else:
                sig = _p_relation_signature(cand, v, g_P, p_orbits)
                by_group[sig].append((v, support))

        for join_idx, v, support in block_join:
            support = dict(support)
            support[n] = v
            if len(support) > 1:
                nc = _refine_sym_assignments(cand, support)
            else:
                nc = cand.with_extended_block(join_idx, n)
                if nc is not None:
                    nc = nc.with_witness(support)
            if nc is not None:
                new_cands.append(nc)

        if not by_group:
            continue
        for _, entries in sorted(by_group.items(), key=lambda kv: str(kv[0])):
            correlated = [(v, support) for v, support in entries if support]
            for v, support in correlated:
                fixed = dict(support)
                fixed[n] = v
                nc = _refine_sym_assignments(cand, fixed)
                if nc is not None:
                    new_cands.append(nc)
            independent = [(v, support) for v, support in entries
                           if not support]
            if not independent:
                continue
            group = tuple(sorted(v for v, _ in independent))
            witness_v, support = sorted(independent, key=lambda item: item[0])[0]
            if len(group) > 1:
                nc = cand.with_new_block(n, group, extendable=True)
            else:
                nc = cand.with_fixed(n, witness_v)
            if nc is not None and isinstance(nc, _SymCand):
                support = dict(support)
                support[n] = witness_v
                nc = nc.with_witness(support)
            if nc is not None:
                new_cands.append(nc)

    sig_fragment = set(fragment_old) | {n}
    for r in island_atoms:
        sig_fragment.add(r)
    return _dedup_sym_cands(
        new_cands, g_R, g_P, r_orbits, p_orbits,
        fragment=sig_fragment, deferred_edges=deferred_edges, inv=inv)


def _merge_whole_island_LEGACY(cands, fragment, n, mapping, islands_R,
                        g_R, g_P, iso_tol):
    """Up-front whole-island merge.

    When propagation reaches an island atom n, pull the ENTIRE island
    (every R-atom whose island_id matches n's) into each cand at once.
    Then check every cross-bond between fragment+island and the rest of
    fragment+island is consistent in P with the existing mapping.

    Returns (new_cands, island_atoms_added). If new_cands is empty, no
    cand survives — caller consumes the edge."""
    if islands_R is None or n not in islands_R:
        # No island bookkeeping; fall back to single-atom semantics.
        island_atoms = [n]
    else:
        target_iid = islands_R[n]
        island_atoms = [r for r, k in islands_R.items() if k == target_iid]
    p_atoms_in_island = [mapping[r] for r in island_atoms]
    new_cands = []
    new_added = [r for r in island_atoms if r not in fragment]
    if not new_added:
        return cands, []  # whole island already absorbed; nothing to do
    for cand in cands:
        # 1) no P-atom in island can be already used by this cand for a
        #    different R-atom
        used_p = set(cand.values())
        if any(p in used_p and cand.get(r) != p
               for r, p in zip(island_atoms, p_atoms_in_island)):
            continue
        # 2) build candidate extension with all island bindings forced
        nc = dict(cand)
        ok = True
        for r, p in zip(island_atoms, p_atoms_in_island):
            if r in nc and nc[r] != p:
                ok = False; break
            nc[r] = p
        if not ok:
            continue
        # 3) check every R-bond between fragment ∪ island (any pair where
        #    at least one endpoint is in island_atoms; the other in
        #    fragment or island_atoms) — the bond must exist in P with
        #    matching WBO. Bonds within fragment alone were checked when
        #    those atoms were added; bonds within island alone are
        #    preserved by construction (the island was locked already).
        check_set = set(island_atoms) | fragment
        for r in island_atoms:
            for r2 in g_R.neighbors(r):
                if r2 not in check_set: continue
                if r2 not in nc:        continue
                if r >= r2 and r2 in island_atoms: continue  # canonicalize
                wR = g_R[r][r2]['wbo']
                p, p2 = nc[r], nc[r2]
                if not g_P.has_edge(p, p2):
                    ok = False; break
                wP = g_P[p][p2]['wbo']
                if abs(wR - wP) > iso_tol:
                    ok = False; break
            if not ok: break
        if ok:
            new_cands.append(nc)
    return new_cands, new_added


def grow_island_pq(g_R, g_P, seed, mapping, inv,
                   graph_floor=0.2,
                   iso_tol=1.0,
                   min_lock_size=1,
                   max_branches=1_000_000,
                   events=None,
                   islands_R=None,
                   p_orbits=None,
                   r_orbits=None,
                   prior_deferred_edges=None):
    """
    Grow a fragment from `seed` using priority-queue propagation.

    Returns a list of isos:
      []            -- failed (no initial cands, or fragment too small)
      [single_iso]  -- locked successfully (set-unique or single cand)
      [iso_a, ...]  -- non-set-unique saturation; caller branches

    Optional `events` list receives diagnostic events (seed_start /
    commit / deferred / merge / seed_end) compatible with the
    existing trace_run.HTML viewer.
    """
    record = events is not None
    if seed in mapping:
        return []
    seed_el = g_R.nodes[seed]['element']
    seed_targets = [v for v in g_P.nodes()
                    if v not in inv and g_P.nodes[v]['element'] == seed_el]
    if p_orbits is not None:
        seed_groups = _group_nodes_by_signature(
            seed_targets, lambda v: (g_P.nodes[v].get('element'),
                                     _orbit_id(p_orbits, v)))
    else:
        seed_groups = [(v,) for v in sorted(seed_targets)]
    cands = []
    for group in seed_groups:
        if len(group) > 1:
            cands.append(_SymCand({seed: group[0]},
                                  (_SymBlock((seed,), group,
                                             extendable=False),)))
        else:
            cands.append(_SymCand({seed: group[0]}))
    if not cands:
        if record:
            events.append({'type': 'seed_start', 'seed': int(seed),
                           'init_cands': 0, 'fragment': [int(seed)],
                           'p_atoms': []})
            events.append({'type': 'seed_end', 'result': 'no_initial_cands',
                           'final_cands': 0, 'fragment': [int(seed)],
                           'iso': None})
        return []
    fragment = {seed}
    distance = {seed: 0}
    used_edges = set()
    deferred_edges = {tuple(sorted(e)) for e in (prior_deferred_edges or ())}
    heap = []
    _push_edges_from(heap, used_edges, g_R, seed, fragment, graph_floor)

    def _cands_sample(cs, k=10):
        return [{int(a): int(b) for a, b in _cand_map(c).items()}
                for c in cs[:k]]

    def _cand_possible_p_atoms(c):
        atoms = set(_cand_map(c).values())
        if isinstance(c, _SymCand):
            for block in c.blocks:
                atoms.update(block.p_atoms)
        return atoms

    def _cand_possible_values(c, r):
        if isinstance(c, _SymCand):
            for block in c.blocks:
                if r in block.r_atoms:
                    return set(block.p_atoms)
        cm = _cand_map(c)
        return {cm[r]} if r in cm else set()

    def _block_assignment_expr(block):
        n = len(block.p_atoms)
        k = len(block.r_atoms)
        if k <= 0 or n <= 1:
            return '1'
        if k == 1:
            return str(n)
        if k == n:
            return f'{n}!'
        return f'P({n},{k})'

    def _cand_assignment_expr(c):
        if not isinstance(c, _SymCand):
            return '1'
        factors = []
        for block in c.blocks:
            expr = _block_assignment_expr(block)
            if expr != '1':
                factors.append(expr)
        return ' * '.join(factors) if factors else '1'

    def _represented_assignment_expr(cs, max_terms=6):
        counts = Counter(_cand_assignment_expr(c) for c in cs)
        if not counts:
            return '0'
        terms = []
        for expr, count in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))[:max_terms]:
            if expr == '1':
                terms.append(str(count))
            elif count == 1:
                terms.append(expr)
            else:
                terms.append(f'{count}*({expr})')
        remaining = max(0, len(counts) - max_terms)
        if remaining:
            terms.append(f'... + {remaining} expression groups')
        return ' + '.join(terms)

    def _cands_pattern_sample(cs, k=5):
        out = []
        for c in cs[:k]:
            item = {
                'witness': {int(a): int(b) for a, b in _cand_map(c).items()},
                'blocks': [],
            }
            if isinstance(c, _SymCand):
                for block in c.blocks:
                    item['blocks'].append({
                        'r_atoms': [int(x) for x in block.r_atoms],
                        'p_atoms': [int(x) for x in block.p_atoms],
                        'extendable': bool(block.extendable),
                        'assignments': _block_assignment_expr(block),
                    })
            out.append(item)
        return out

    if record:
        events.append({
            'type': 'seed_start',
            'seed': int(seed),
            'init_cands': len(cands),
            'represented_assignments': _represented_assignment_expr(cands),
            'fragment': [int(seed)],
            'p_atoms': sorted({int(v) for c in cands
                               for v in _cand_possible_p_atoms(c)}),
            'cand_patterns': _cands_pattern_sample(cands, 5),
        })

    def _heap_snapshot(k=None):
        """Pending heap entries sorted by WBO desc, filtered to live
        (not yet popped, not already in fragment). k=None → all."""
        peek = list(heap)
        peek.sort()
        live = [(w, uu, nn) for (w, uu, nn) in peek
                if frozenset({uu, nn}) not in used_edges and nn not in fragment]
        if k is not None:
            live = live[:k]
        return [{'frag_atom': int(uu), 'ext_atom': int(nn),
                 'wbo': round(-w, 3),
                 'ext_status': ('mapped' if nn in mapping
                                else 'free')}
                for w, uu, nn in live]

    def _pool_by_frag_atom():
        """Live propagation pool grouped by fragment atom. Each atom's
        outgoing live edges sorted WBO desc."""
        peek = list(heap)
        peek.sort()
        by_u = defaultdict(list)
        for w, uu, nn in peek:
            if frozenset({uu, nn}) in used_edges: continue
            if nn in fragment: continue
            by_u[int(uu)].append({
                'ext_atom': int(nn),
                'wbo': round(-w, 3),
                'ext_status': ('mapped' if nn in mapping else 'free'),
                'ext_element': g_R.nodes[nn]['element'],
            })
        return [{'frag_atom': int(u),
                 'frag_element': g_R.nodes[u]['element'],
                 'edges': sorted(by_u[u], key=lambda x: -x['wbo'])}
                for u in sorted(by_u.keys())]

    def _why_extend_failed(n_atom, anchor_atom=None, anchor_wbo=None):
        """Per-cand explanation of why extension to n_atom failed."""
        bonded = sorted(fragment)
        n_el = g_R.nodes[n_atom]['element']
        r_wbos = [(u, _edge_wbo(g_R, u, n_atom)) for u in bonded]
        strict_r_wbos = {}
        if anchor_atom is not None and anchor_atom in fragment:
            strict_r_wbos[anchor_atom] = (
                _edge_wbo(g_R, anchor_atom, n_atom)
                if anchor_wbo is None else anchor_wbo
            )
        out = []
        for ci, cand in enumerate(cands[:5]):
            cm = _cand_map(cand)
            used_p = _cand_possible_p_atoms(cand)
            v_set = {
                v for v in g_P.nodes()
                if v not in used_p and v not in inv
                and g_P.nodes[v]['element'] == n_el
            }
            tried = []
            for v in sorted(v_set)[:30]:
                why = []
                _, p_to_block = _sym_block_indexes(cand)
                join_idx = p_to_block.get(v)
                support = _support_witness_for_value(
                    cand, n_atom, v, bonded, r_wbos, g_P, iso_tol,
                    join_block_idx=join_idx,
                    strict_r_wbos=strict_r_wbos)
                if support is None:
                    bad = []
                    for u, w in r_wbos:
                        if u not in cm:
                            continue
                        wp = _edge_wbo(g_P, cm[u], v)
                        if u in strict_r_wbos:
                            if not _growth_edge_supported(
                                    strict_r_wbos[u], wp, iso_tol):
                                bad.append(f'R[{u}]: growth edge |{w:.3f}-{wp:.3f}|={abs(w-wp):.3f} bucket/nonzero fail')
                        elif abs(w - wp) > iso_tol:
                            bad.append(f'R[{u}]: |{w:.3f}-{wp:.3f}|={abs(w-wp):.3f}>{iso_tol}')
                    why.append('; '.join(bad[:5]) if bad else 'no block witness')
                tried.append({'v': int(v), 'rejected': bool(why),
                              'reason': '; '.join(why) if why else 'OK'})
            out.append({
                'cand_idx': ci,
                'cand_at_in_frag_neighbors': {int(u): int(cm[u]) for u in bonded},
                'candidate_v_count': len(v_set),
                'tried_v': tried,
            })
        return out

    def _why_merge_failed(n_atom):
        """Per-cand explanation of why whole-island merge to n_atom failed."""
        if islands_R is None or n_atom not in islands_R:
            island_atoms = [n_atom]
        else:
            target_iid = islands_R[n_atom]
            island_atoms = [r for r, k in islands_R.items() if k == target_iid]
        out = []
        for ci, cand in enumerate(cands[:5]):
            cm = _cand_map(cand)
            why = []
            used_p = set(cm.values())
            for r in island_atoms:
                p = mapping[r]
                if p in used_p and cm.get(r) != p:
                    owner = [k for k, v in cm.items() if v == p][0]
                    why.append(f'P[{p}] (image of R[{r}]) already used by R[{owner}]')
                if r in cm and cm[r] != p:
                    why.append(f'R[{r}] in cand as P[{cm[r]}], conflicts with mapping P[{p}]')
            # cross-bond check
            nc = dict(cm)
            for r, p in [(r, mapping[r]) for r in island_atoms if r not in nc]:
                nc[r] = p
            check_set = set(island_atoms) | fragment
            for r in island_atoms:
                for r2 in sorted(check_set):
                    if r2 == r:
                        continue
                    if r2 not in check_set or r2 not in nc: continue
                    if r >= r2 and r2 in island_atoms: continue
                    wR = _edge_wbo(g_R, r, r2)
                    p, p2 = nc[r], nc[r2]
                    wP = _edge_wbo(g_P, p, p2)
                    if abs(wR - wP) > iso_tol:
                        why.append(f'R[{r}]-R[{r2}]: |{wR:.3f}-{wP:.3f}|={abs(wR-wP):.3f} (P[{p}]-P[{p2}])')
            out.append({'cand_idx': ci, 'reasons': why[:8]})
        return out

    while heap:
        if _set_unique(cands) and len(cands) == 1 and len(fragment) >= min_lock_size:
            if record:
                iso = {int(k): int(v) for k, v in _cand_map(cands[0]).items()}
                events.append({
                    'type': 'seed_end', 'result': 'success',
                    'final_cands': 1,
                    'fragment': sorted(int(x) for x in fragment),
                    'iso': iso,
                    'all_isos': [iso],
                    'lock_reason': 'set_unique_len1_during_BFS',
                    'heap_remaining': len(heap),
                    'cand_patterns': _cands_pattern_sample(cands, 5),
                })
            return [_IsoResult(_cand_map(cands[0]),
                               deferred_edges=deferred_edges,
                               fragment=fragment)]

        neg_w, u, n = heapq.heappop(heap)
        wbo = -neg_w
        edge = frozenset({u, n})
        if edge in used_edges:
            continue
        used_edges.add(edge)
        if n in fragment:
            if record:
                events.append({
                    'type': 'pop_skip',
                    'edge': {'frag_atom': int(u), 'ext_atom': int(n), 'wbo': round(wbo, 3)},
                    'reason': 'ext_atom already in fragment',
                })
            continue

        n_in_mapping = n in mapping
        if record:
            events.append({
                'type': 'pop',
                'edge': {'frag_atom': int(u), 'ext_atom': int(n),
                         'wbo': round(wbo, 3),
                         'ext_element': g_R.nodes[n]['element']},
                'scenario': ('merge_island' if n_in_mapping else 'extend_free'),
                'island_id_at_ext': (int(islands_R[n]) if islands_R and n in islands_R else None),
                'island_image': (int(mapping[n]) if n_in_mapping else None),
                'pre_state': {
                    'fragment_size': len(fragment),
                    'fragment': sorted(int(x) for x in fragment),
                    'cands_count': len(cands),
                    'represented_assignments': _represented_assignment_expr(cands),
                    'cands_sample': _cands_sample(cands, 5),
                    'cands_pattern_sample': _cands_pattern_sample(cands, 5),
                    'p_atoms_in_cands': sorted({int(v) for c in cands
                                                for v in _cand_possible_p_atoms(c)}),
                },
                'heap_top_after_pop': _heap_snapshot(8),
                'pool_by_frag_atom': _pool_by_frag_atom(),
            })

        # Tentatively add n to the shared fragment. If any weighted extension
        # survives, commit it; otherwise record this edge as deferred boundary.
        old_count = len(cands)
        old_fragment = set(fragment)
        candidate_fragment = fragment | {n}
        # Symmetry-compressed incremental extension.  It applies the same
        # element/WBO checks as the concrete incremental matcher, but groups
        # target atoms by local orbit/context before constructing children.
        new_cands = _extend_sym_cands(
            cands, fragment, n, g_R, g_P, mapping, inv,
            iso_tol, islands_R, p_orbits=p_orbits, r_orbits=r_orbits,
            deferred_edges=deferred_edges, anchor_u=u, anchor_wbo=wbo)
        if new_cands:
            cands = new_cands
            ref_dist = distance.get(u, 0) + 1
            if n_in_mapping and islands_R is not None and n in islands_R:
                target_iid = islands_R[n]
                whole_island = [r for r, k in islands_R.items() if k == target_iid]
                candidate_fragment = candidate_fragment | set(whole_island)
                added_extra = [r for r in whole_island if r not in distance]
                for r in added_extra:
                    distance[r] = ref_dist
            fragment = candidate_fragment
            for r in fragment - old_fragment:
                if r not in distance:
                    distance[r] = ref_dist
                _push_edges_from(heap, used_edges, g_R, r, fragment, graph_floor)
            if record:
                added_atoms = sorted(int(r) for r in fragment - old_fragment)
                events.append({
                    'type': 'commit',
                    'scenario': ('merge_island' if n_in_mapping else 'extend_free'),
                    'edge': {'frag_atom': int(u), 'ext_atom': int(n), 'wbo': round(wbo, 3)},
                    'added': int(n), 'element': g_R.nodes[n]['element'],
                    'atoms_added': added_atoms,
                    'island_size_absorbed': len(added_atoms) if n_in_mapping else None,
                    'island_image': int(mapping[n]) if n_in_mapping else None,
                    'cand_n_value_set': sorted({int(v) for c in cands
                                                for v in _cand_possible_values(c, n)}),
                    'cands_before': old_count,
                    'cands_after': len(cands),
                    'represented_assignments_after': _represented_assignment_expr(cands),
                    'cands_sample_after': _cands_sample(cands, 5),
                    'cands_pattern_after': _cands_pattern_sample(cands, 5),
                    'fragment': sorted(int(x) for x in fragment),
                    'p_atoms': sorted({int(v) for c in cands
                                       for v in _cand_possible_p_atoms(c)}),
                    'distance_from_seed': distance[n],
                    'bonds_to_fragment': [(int(u), round(wbo, 3))],
                    'heap_remaining': len(heap),
                    'heap_top': _heap_snapshot(8),
                    'pool_by_frag_atom': _pool_by_frag_atom(),
                })
        else:
            deferred_edges.add(tuple(sorted((u, n))))
            if record:
                events.append({
                    'type': 'consumed',
                    'deferred': True,
                    'scenario': ('merge_island' if n_in_mapping else 'extend_free'),
                    'edge': {'frag_atom': int(u), 'ext_atom': int(n), 'wbo': round(wbo, 3),
                             'ext_element': g_R.nodes[n]['element']},
                    'reason': ('merge_failed' if n_in_mapping else 'cut_all_cands'),
                    'island_image': int(mapping[n]) if n_in_mapping else None,
                    'island_id': int(islands_R[n]) if islands_R and n in islands_R else None,
                    'why_per_cand': (_why_merge_failed(n) if n_in_mapping
                                     else _why_extend_failed(n, u, wbo)),
                    'cands_count': len(cands),
                    'represented_assignments': _represented_assignment_expr(cands),
                    'cands_sample': _cands_sample(cands, 5),
                    'cands_pattern_sample': _cands_pattern_sample(cands, 5),
                    'fragment': sorted(int(x) for x in fragment),
                    'heap_remaining': len(heap),
                    'heap_top': _heap_snapshot(8),
                    'pool_by_frag_atom': _pool_by_frag_atom(),
                })

    # heap empty
    if not cands or len(fragment) < min_lock_size:
        if record:
            events.append({
                'type': 'seed_end',
                'result': ('no_cands' if not cands else 'too_small'),
                'final_cands': len(cands),
                'fragment': sorted(int(x) for x in fragment),
                'iso': None,
            })
        return []
    if _set_unique(cands):
        if record:
            iso_map = _cand_map(cands[0])
            iso = {int(k): int(v) for k, v in iso_map.items()}
            events.append({
                'type': 'seed_end', 'result': 'success',
                'final_cands': len(cands),
                'fragment': sorted(int(x) for x in fragment),
                'iso': iso,
                'all_isos': [iso],
                'cand_patterns': _cands_pattern_sample(cands, 5),
            })
        return [_IsoResult(_cand_map(cands[0]),
                           deferred_edges=deferred_edges,
                           fragment=fragment)]
    # Dedup by compressed structural signature.  Open symmetry blocks may
    # still contain many concrete witnesses; only one deterministic witness
    # is returned for each orbit/context-distinct saturation.
    by_set = {}
    for c in cands:
        if isinstance(c, _SymCand):
            key = (
                c.structural_signature(g_R, g_P, r_orbits, p_orbits),
                _boundary_signature(
                    c, g_R, g_P, fragment=fragment,
                    deferred_edges=deferred_edges, r_orbits=r_orbits,
                    p_orbits=p_orbits, inv=inv),
            )
        elif p_orbits is not None:
            key = (
                _cand_canon_signature(c, p_orbits),
                _boundary_signature(
                    c, g_R, g_P, fragment=fragment,
                    deferred_edges=deferred_edges, r_orbits=r_orbits,
                    p_orbits=p_orbits, inv=inv),
            )
        else:
            key = (
                tuple(sorted(c.items())),
                _boundary_signature(
                    c, g_R, g_P, fragment=fragment,
                    deferred_edges=deferred_edges, r_orbits=r_orbits,
                    p_orbits=p_orbits, inv=inv),
            )
        if key not in by_set:
            by_set[key] = _IsoResult(
                _cand_map(c), deferred_edges=deferred_edges,
                fragment=fragment)
    branches = list(by_set.values())[:max_branches]
    if record:
        events.append({
            'type': 'seed_end', 'result': 'branched',
            'final_cands': len(cands), 'n_branches': len(branches),
            'fragment': sorted(int(x) for x in fragment),
            'iso': {int(k): int(v) for k, v in branches[0].items()},
            'all_isos': [{int(k): int(v) for k, v in c.items()}
                         for c in branches],
            'cand_patterns': _cands_pattern_sample(cands, 10),
        })
    return branches


# -------------------- BFS frontier search --------------------

def grow_island_bfs(g_R, g_P, seed, mapping, inv,
                    graph_floor=0.2, iso_tol=1.0,
                    min_lock_size=1, events=None,
                    islands_R=None, max_branches=1_000_000):
    """EXPERIMENTAL: BFS frontier search over partial mappings.

    Status: kept for reference, not wired into find_islands_pq because
    it explodes on real molecules. The naive BFS spawns one child per
    valid (R_neighbor, P_target) extension; even with mapping-signature
    dedup, the state space grows multiplicatively because different
    growth orders can land on different INTERMEDIATE mappings that don't
    converge until very late.

    The current grow_island_pq avoids this by maintaining ONE shared
    fragment (deterministic growth order via WBO heap) and tracking
    multiple bijections of that single fragment as the cands list. The
    result is the same set of saturation bijections, but with bounded
    intermediate state count.

    A working BFS replacement would need either:
      - a canonical fragment-growth order (e.g., always extend the
        lowest-index frontier atom) so all states share a fragment, OR
      - a smarter dedup that canonicalizes mappings up to spectator
        permutations earlier in the search.

    Left here as a starting point for future work.
    """
    record = events is not None
    if seed in mapping:
        return []
    seed_el = g_R.nodes[seed]['element']

    init_isos = []
    for v in g_P.nodes():
        if v in inv: continue
        if g_P.nodes[v]['element'] != seed_el: continue
        init_isos.append({seed: v})

    if not init_isos:
        if record:
            events.append({'type': 'seed_start', 'seed': int(seed),
                           'init_cands': 0, 'fragment': [int(seed)],
                           'p_atoms': []})
            events.append({'type': 'seed_end', 'result': 'no_initial_cands',
                           'final_cands': 0, 'fragment': [int(seed)],
                           'iso': None})
        return []

    if record:
        events.append({'type': 'seed_start', 'seed': int(seed),
                       'init_cands': len(init_isos),
                       'fragment': [int(seed)],
                       'p_atoms': sorted(int(c[seed]) for c in init_isos)})

    # Frontier: set of frozensets of (R, P) pairs. Use frozenset for O(1)
    # dedup of partial-mapping states.
    frontier = {frozenset(m.items()) for m in init_isos}
    saturated = set()
    bfs_level = 0

    while frontier:
        bfs_level += 1
        next_frontier = set()
        for state in frontier:
            m = dict(state)
            mapped_R = set(m.keys())
            mapped_P = set(m.values())
            extensions_made = False
            # Iterate every fragment atom; for each, enumerate every
            # valid (n, v) extension. The dedup at next_frontier collapses
            # duplicates from different atom-pick orders.
            for r in mapped_R:
                for n in g_R.neighbors(r):
                    if n in mapped_R: continue
                    if g_R[r][n]['wbo'] < graph_floor: continue
                    if n in mapping: continue  # globally locked
                    n_el = g_R.nodes[n]['element']
                    bonded_to_n = [u for u in g_R.neighbors(n)
                                   if u in mapped_R
                                   and g_R[u][n]['wbo'] >= graph_floor]
                    if not bonded_to_n: continue
                    p_cands = set(g_P.neighbors(m[bonded_to_n[0]]))
                    for u in bonded_to_n[1:]:
                        p_cands &= set(g_P.neighbors(m[u]))
                    p_cands -= mapped_P
                    p_cands -= set(inv.keys())
                    for v in p_cands:
                        if g_P.nodes[v]['element'] != n_el: continue
                        ok = True
                        for u in bonded_to_n:
                            wR = g_R[u][n]['wbo']
                            wP = g_P[m[u]][v]['wbo']
                            if abs(wR - wP) > iso_tol:
                                ok = False; break
                        if not ok: continue
                        new_m = dict(m); new_m[n] = v
                        next_frontier.add(frozenset(new_m.items()))
                        extensions_made = True
            if not extensions_made:
                saturated.add(state)
        frontier = next_frontier
        if len(saturated) > max_branches:
            break

    # Saturation can produce many tied bijections (different P targets for
    # symmetric atoms). The frozenset already deduped by mapping signature,
    # so just convert back to dicts.
    result = []
    for fro in saturated:
        m = {r: v for r, v in fro}
        if len(m) >= min_lock_size:
            result.append(m)

    if record:
        if not result:
            events.append({'type': 'seed_end',
                           'result': 'no_cands' if not saturated else 'too_small',
                           'final_cands': 0,
                           'fragment': [int(seed)],
                           'iso': None})
        else:
            ref_frag = sorted(int(x) for x in result[0].keys())
            iso0 = {int(k): int(v) for k, v in result[0].items()}
            evt = {
                'type': 'seed_end',
                'result': 'success' if len(result) == 1 else 'branched',
                'final_cands': len(result),
                'n_branches': len(result),
                'fragment': ref_frag,
                'iso': iso0,
                'all_isos': [{int(k): int(v) for k, v in m.items()}
                             for m in result],
                'bfs_levels': bfs_level,
            }
            events.append(evt)
    return result


